#!/usr/bin/env python3
"""Owned-emulator fixture: real API3 archives/state plus explicitly synthetic runtime sentinels.
api3-state.json was generated by the production PackageStore, not by an alternate store serializer.
No installed JDK/Ubuntu distribution is embedded or claimed.
"""
from pathlib import Path
import argparse,hashlib,json,tarfile,io
root=Path(__file__).resolve().parents[2]
def build(output):
 output.mkdir(parents=True,exist_ok=True)
 state=(root/'tools/startup/fixtures/api3-state.json').read_bytes()
 files={'files/sui-code/native-packages/state.json':state}
 for item in json.loads(state).values():
  name=item['digest']+'.'+item['kind']
  candidates=[p for p in (root/'native-library/v1').glob('*.'+item['kind']) if hashlib.sha256(p.read_bytes()).hexdigest()==item['digest']]
  assert len(candidates)==1,name
  files['files/sui-code/native-packages/'+name]=candidates[0].read_bytes()
 files.update({
  'files/workspace/projects/Startup Project/中文 + Hello.java':b'public class Hello { public static void main(String[] args) { System.out.println("preserve"); } }\n',
  'files/workspace/projects/Startup Project/.jcode/run.yaml':b'runs:\n  - name: legacy task\n    command: echo preserved\n',
  'files/distros/fixture-v05/rootfs/opt/sui-code/java.env':b'export JAVA_HOME=/opt/sui-code/jdks/temurin-existing\n',
  'files/distros/fixture-v05/rootfs/opt/sui-code/jdks/temurin-existing/SUI_TEST_SENTINEL':b'JDK retention sentinel, not an installed executable JDK\n',
  'files/distros/fixture-v05/rootfs/opt/sui-code/python.env':b'# retained Python configuration sentinel\n',
  'files/distros/fixture-v05/rootfs/opt/sui-code/c.env':b'# retained C configuration sentinel\n'})
 with tarfile.open(output/'payload.tar','w') as archive:
  for name,data in files.items():
   entry=tarfile.TarInfo(name);entry.size=len(data);entry.mode=0o600;archive.addfile(entry,io.BytesIO(data))
 (output/'payload-sha256.json').write_text(json.dumps({name:hashlib.sha256(data).hexdigest() for name,data in files.items()},ensure_ascii=False,indent=2)+'\n')
 print('Built',len(files),'data-retention fixture files')
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('output',type=Path);build(p.parse_args().output)
