#!/usr/bin/env python3
"""Generate/check the Core English catalog and closed API4 resource schema.
Translations are separate .suik source files, never Android resources or APK assets.
"""
from pathlib import Path
import json,re,sys
ROOT=Path(__file__).resolve().parents[2]
def quote(value):return json.dumps(value,ensure_ascii=False).replace('$','\\$')
def main(write=False):
    english=json.loads((ROOT/'localization/en.json').read_text())
    assert len(english)==len(set(english))
    assert all(re.fullmatch(r'[a-z][a-zA-Z0-9.]+',k) for k in english)
    assert all(isinstance(v,str) and 0<len(v)<=2048 for v in english.values())
    block='object UiTextKeys {\n    // Generated by tools/localization/catalog.py from localization/en.json.\n    val english: Map<String,String> = mapOf(\n'+',\n'.join('        '+quote(k)+' to '+quote(v) for k,v in english.items())+'\n    )\n}\n'
    path=ROOT/'core/native-packages/src/main/java/dev/suicode/packages/Localization.kt'
    source=path.read_text();a=source.index('object UiTextKeys {');b=source.index('\ndata class LocalizationDescriptor',a)
    expected=source[:a]+block+source[b:]
    schema={'$schema':'https://json-schema.org/draft/2020-12/schema','type':'object','additionalProperties':False,'minProperties':1,'maxProperties':len(english),'properties':{k:{'type':'string','minLength':1,'maxLength':2048} for k in english}}
    sp=ROOT/'docs/specifications/schemas/localization-resources.schema.json';encoded=json.dumps(schema,ensure_ascii=False,indent=2)+'\n'
    if write:path.write_text(expected);sp.write_text(encoded)
    else:
        assert source==expected,'E_CATALOG_STALE: regenerate Core English'
        assert sp.read_text()==encoded,'E_CATALOG_STALE: regenerate closed schema'
    print('Core catalog/schema:',len(english),'keys; API 4, resource limit 65536 bytes unchanged')
if __name__=='__main__':main('--write' in sys.argv)
